// Builds the nickname filter from the word lists and writes it into the game and the Firestore rules.
//   moderation/ldnoobw/*.txt   LDNOOBW lists (CC BY 4.0, github.com/LDNOOBW), one word or phrase per line
//   moderation/custom.txt      languages and slang those lists miss (~ anywhere, = whole word)
//   moderation/drop.txt        everyday words removed from the lists
//   moderation/exact.txt       long entries that only count as a whole word
// Usage: node build-name-filter.mjs
import fs from 'node:fs';

const here = p => new URL(p, import.meta.url);
const LEET = { 0: 'o', 1: 'i', 3: 'e', 4: 'a', 5: 's', 7: 't', 8: 'b', 9: 'g', '@': 'a', $: 's', '!': 'i', '|': 'i' };
export const norm = s => String(s).toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[0-9@$!|]/g, c => LEET[c] || c);
const joined = s => norm(s).replace(/[^a-z]/g, '');
const words = f => fs.readFileSync(here(f), 'utf8').split('\n').filter(l => l.trim() && !l.startsWith('#')).flatMap(l => l.trim().split(/\s+/)).map(joined);

const drop = new Set(words('drop.txt')), exact = new Set(words('exact.txt')), allow = words('allow.txt').sort((a, b) => b.length - a.length);
const sub = new Set(), word = new Set();
const add = (raw, tier) => {
  const w = joined(raw);
  if (w.length < 2 || drop.has(w)) return;
  if (tier === '~') sub.add(w);
  else if (tier === '=' || exact.has(w) || w.length <= 4) word.add(w);
  else sub.add(w);
};
for (const f of fs.readdirSync(here('ldnoobw/')).filter(f => f.endsWith('.txt') && f !== 'ar.txt')) {
  fs.readFileSync(here('ldnoobw/' + f), 'utf8').split('\n').forEach(l => { if (l.trim()) add(l.trim(), ''); });
}
fs.readFileSync(here('custom.txt'), 'utf8').split('\n').forEach(l => {
  l = l.trim(); if (!l || l.startsWith('#')) return;
  const tier = l[0] === '~' || l[0] === '=' ? l[0] : '';
  add(tier ? l.slice(1) : l, tier);
});
/* names are at most 16 characters, so longer entries can never match */
for (const w of [...sub]) if (w.length > 16) sub.delete(w);
for (const w of [...word]) if (w.length > 16) word.delete(w);
/* a stem that contains a shorter stem adds nothing */
const subs = [...sub].sort((a, b) => a.length - b.length).filter((w, i, all) => !all.slice(0, i).some(s => w.includes(s)));
const wordsOut = [...word].filter(w => !subs.some(s => w.includes(s))).sort();
fs.writeFileSync(here('name-filter.json'), JSON.stringify({ sub: subs, word: wordsOut, allow }, null, 1));

/* game: the data block between the markers */
const block = `/* name-filter:start (generated by moderation/build-name-filter.mjs from LDNOOBW lists, CC BY 4.0, and hand-written lists) */\n  const NAME_SUB = ${JSON.stringify(subs.join(' '))}.split(' '), NAME_WORD = new Set(${JSON.stringify(wordsOut.join(' '))}.split(' '));\n  const NAME_ALLOW = new RegExp(${JSON.stringify(allow.join('|'))}, 'g');\n  /* name-filter:end */`;
const gameFile = here('../game/index.html');
const game = fs.readFileSync(gameFile, 'utf8');
const gm = /\/\* name-filter:start[\s\S]*?\/\* name-filter:end \*\//;
if (!gm.test(game)) throw new Error('game: name-filter markers not found');
fs.writeFileSync(gameFile, game.replace(gm, block));

/* Firestore allows regular expressions of at most 4096 characters, so long alternations are split */
const chunks = list => { const out = [[]]; let len = 0; for (const w of list) { if (len + w.length + 1 > 3900) { out.push([]); len = 0; } out[out.length - 1].push(w); len += w.length + 1; } return out; };
/* Firestore rules: the same test, without accent folding or repeated-letter squashing (rules cannot do those) */
const leetChain = Object.entries(LEET).map(([k, v]) => `.replace('${/[$|]/.test(k) ? '[' + k + ']' : k}', '${v}')`).join('');
const rules = `// name-filter:start (generated by moderation/build-name-filter.mjs)
    function nameText(n) {
      return n.lower()${leetChain};
    }
    function cleanName(n) {
      return ${chunks(subs).map(c => `!nameText(n).replace('[^a-z]', '').replace('${allow.join('|')}', '').matches('.*(${c.join('|')}).*')`).join('\n        && ')}
        && ${chunks(wordsOut).map(c => `!('-' + nameText(n).replace('[^a-z]+', '-') + '-').matches('.*-(${c.join('|')})-.*')\n        && !('-' + n.lower().replace('[^a-z]+', '-') + '-').matches('.*-(${c.join('|')})-.*')`).join('\n        && ')};
    }
    // name-filter:end`;
const rulesFile = here('../backend/firestore.rules');
const rf = fs.readFileSync(rulesFile, 'utf8');
const rm = /\/\/ name-filter:start[\s\S]*?\/\/ name-filter:end/;
if (!rm.test(rf)) throw new Error('rules: name-filter markers not found');
fs.writeFileSync(rulesFile, rf.replace(rm, rules));
console.log(`name filter: ${subs.length} stems that match anywhere, ${wordsOut.length} whole words; rules ${Math.round(rules.length / 1024)} KB`);
